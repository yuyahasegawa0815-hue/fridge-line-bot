// LINE から開く画面の言葉。トークのリンクに付いた ?l=（言語）を覚えておき、画面を移動しても引き継ぐ。
export function currentLang(): Lang {
  const fromUrl = new URLSearchParams(location.search).get("l");
  try {
    if (isLang(fromUrl)) sessionStorage.setItem("fridgy-l", fromUrl);
    const saved = sessionStorage.getItem("fridgy-l");
    return isLang(fromUrl) ? fromUrl : isLang(saved) ? saved : "ja";
  } catch {
    return isLang(fromUrl) ? fromUrl : "ja";
  }
}

