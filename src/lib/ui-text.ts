const ALL: Record<Lang, UiText> = { ja, en, fr, ko, zh };

export interface Ui extends UiText {
  lang: Lang;
  yen: (n: number) => string;
  category: (c: string) => string;
}

export function uiFor(lang: Lang): Ui {
  return { ...ALL[lang], lang, yen: (n) => formatYen(n, lang), category: (c) => categoryLabel(c, lang) };
}

// 画面の言葉。ブラウザで URL を読むまでは言語がわからないので、読み込み中の表示だけ言葉なしにする。
export function useUi(): Ui {
  const [lang, setLang] = useState<Lang | null>(null);
  useEffect(() => {
    const l = currentLang();
    document.documentElement.lang = l;
    setLang(l);
  }, []);
  const ui = uiFor(lang ?? "ja");
  return lang ? ui : { ...ui, loading: "…" };
}
